/* Progressive enhancement: Django HTML remains the source of truth and works without JS. */
(() => {
  let pending = false;
  let activeController;
  let generation = 0;
  const currentMain = () => document.querySelector('main.account-main, main.auth-main');
  const isAccountUrl = value => {
    const url = new URL(value, location.href);
    return url.origin === location.origin && url.pathname.startsWith('/accounts/') &&
      !url.pathname.includes('/google/') && !url.pathname.includes('/verify/');
  };
  function announce(message, error = false) {
    let box = document.getElementById('account-request-status');
    if (!box) {
      box = document.createElement('p');
      box.id = 'account-request-status';
      box.className = 'account-request-status';
      box.setAttribute('role', 'status');
      box.setAttribute('aria-live', 'polite');
      currentMain()?.prepend(box);
    }
    box.textContent = message;
    box.classList.toggle('account-request-error', error);
  }
  async function navigate(url, options = {}, push = true) {
    if (pending || !currentMain()) return;
    pending = true;
    const requestGeneration = ++generation;
    const controller = new AbortController();
    activeController = controller;
    const source = currentMain();
    source.setAttribute('aria-busy', 'true');
    announce('Saving or loading your account...');
    try {
      const response = await fetch(url, {...options, credentials: 'same-origin',
        headers: {...options.headers, 'Accept': 'text/html'}, signal: controller.signal});
      if (requestGeneration !== generation) return;
      if (new URL(response.url).origin !== location.origin) throw new Error('Unexpected destination.');
      if (!response.ok) {
        const messages = {403: 'Your session or security token has expired. Reload the page and try again.',
          404: 'This page or item is no longer available.', 429: 'Please wait before trying again.'};
        throw new Error(messages[response.status] || 'The request could not be completed. Please try again.');
      }
      const html = new DOMParser().parseFromString(await response.text(), 'text/html');
      if (requestGeneration !== generation) return;
      const next = html.querySelector('main.account-main, main.auth-main');
      if (!next) { location.assign(response.url); return; }
      // Parse HTML generated by our own Django templates; user values are template-escaped.
      source.replaceWith(next);
      const actions = document.querySelector('.gaia-navbar .nav-actions');
      if (actions) {
        actions.querySelectorAll('a').forEach(node => node.remove());
        html.querySelectorAll('.gaia-navbar .nav-actions a').forEach(node => actions.append(node));
      }
      const drawerAccount = document.querySelector('.site-drawer-account');
      const newDrawerAccount = html.querySelector('.site-drawer-account');
      if (drawerAccount && newDrawerAccount) drawerAccount.replaceWith(newDrawerAccount);
      const oldDialog = document.querySelector('#logout-dialog');
      const newDialog = html.querySelector('#logout-dialog');
      if (oldDialog && newDialog) oldDialog.replaceWith(newDialog);
      else if (oldDialog) oldDialog.remove();
      else if (newDialog) document.body.append(newDialog);
      // Page styles are retained for later visits; scripts initialize through accounts:updated.
      html.querySelectorAll('link[rel="stylesheet"]').forEach(link => {
        if (!Array.from(document.querySelectorAll('link[rel="stylesheet"]')).some(old => old.href === link.href))
          document.head.append(link);
      });
      // Login rotates the CSRF secret; refresh every surviving form, including the bag drawer.
      const token = html.querySelector('[name=csrfmiddlewaretoken]')?.value;
      if (token) document.querySelectorAll('[name=csrfmiddlewaretoken]').forEach(field => { field.value = token; });
      document.title = html.title;
      if (push) history.pushState({}, '', response.url);
      document.dispatchEvent(new CustomEvent('accounts:updated'));
      const target = next.querySelector('[aria-invalid="true"], .errorlist, h1, h2');
      if (target) { target.setAttribute('tabindex', '-1'); target.focus({preventScroll: true}); }
      window.scrollTo({top: 0, behavior: 'instant'});
      announce(next.querySelector('.errorlist') ? 'Please correct the highlighted fields.' : 'Account updated.');
    } catch (error) {
      if (error.name === 'AbortError' || requestGeneration !== generation) return;
      announce(error.message || 'Network error. Your input has been kept; please try again.', true);
    } finally {
      if (requestGeneration === generation) {
        pending = false;
        activeController = null;
        currentMain()?.removeAttribute('aria-busy');
      }
    }
  }
  document.addEventListener('submit', event => {
    const form = event.target;
    if (!(form instanceof HTMLFormElement) || form.method.toLowerCase() !== 'post' ||
        !form.closest('main.account-main, main.auth-main, #logout-dialog')) return;
    const action = new URL(form.action || location.href, location.href);
    if (action.origin !== location.origin || action.pathname.includes('/google/')) return;
    if (!form.checkValidity()) return;
    event.preventDefault();
    if (pending) return;
    const data = new FormData(form);
    if (event.submitter?.name) data.append(event.submitter.name, event.submitter.value);
    navigate(action.href, {method: 'POST', body: data});
  });
  document.addEventListener('click', event => {
    const link = event.target.closest('a[href]');
    if (!link || event.defaultPrevented || event.button !== 0 || event.metaKey || event.ctrlKey ||
        event.shiftKey || event.altKey || link.target || link.download || !currentMain()) return;
    if (!link.closest('main.account-main, main.auth-main') || !isAccountUrl(link.href)) return;
    event.preventDefault();
    navigate(link.href);
  });
  window.addEventListener('popstate', () => {
    activeController?.abort();
    generation += 1;
    pending = false;
    if (isAccountUrl(location.href)) navigate(location.href, {}, false);
    else location.reload();
  });
})();
